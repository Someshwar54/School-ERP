"""Export the OpenAPI schema and a Markdown endpoint index (keeps docs/API.md in sync with code).

python -m app.tools.export_openapi            # writes ../docs/openapi.json and ../docs/API_ENDPOINTS.md
"""

import json
from pathlib import Path

from app.main import app

DOCS = Path(__file__).resolve().parents[3] / "docs"


def main() -> None:
    schema = app.openapi()
    (DOCS / "openapi.json").write_text(json.dumps(schema, indent=2) + "\n")
    rows: dict[str, list[str]] = {}
    for path, ops in schema["paths"].items():
        for method, op in ops.items():
            tag = (op.get("tags") or ["other"])[0]
            summary = op.get("summary") or op.get("operationId", "")
            rows.setdefault(tag, []).append(f"| `{method.upper()}` | `{path}` | {summary} |")
    lines = [
        "# API endpoint index",
        "",
        "Generated by `python -m app.tools.export_openapi` from the running code. Do not edit by hand.",
        "Interactive docs: `http://localhost:8000/api/docs` (development). Full schema: [openapi.json](openapi.json).",
        "",
    ]
    for tag in sorted(rows):
        lines += [f"## {tag}", "", "| Method | Path | Summary |", "|---|---|---|", *rows[tag], ""]
    (DOCS / "API_ENDPOINTS.md").write_text("\n".join(lines))
    print(f"Wrote {DOCS / 'openapi.json'} and {DOCS / 'API_ENDPOINTS.md'} ({sum(len(v) for v in rows.values())} endpoints)")


if __name__ == "__main__":
    main()
